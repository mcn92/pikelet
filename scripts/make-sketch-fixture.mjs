// Regenerate test/fixtures/sketch_golden.js — the sketch profile conformance
// fixture: a small deterministic artifact plus the reference reader's exact
// results. Run: node scripts/make-sketch-fixture.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Pikelet from '../pikelet.node.mjs';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const COUNT = 256;
const DIM = 32;
const SEED = 20260802;

function seededRows(count, dim, seed) {
  let s = seed >>> 0;
  const next = () => { s = (Math.imul(s, 1664525) + 1013904223) >>> 0; return s / 0xffffffff; };
  const rows = [];
  for (let i = 0; i < count; i++) {
    const v = new Float32Array(dim);
    let prev = next() * 2 - 1;
    for (let d = 0; d < dim; d++) { prev = 0.75 * prev + 0.25 * (next() * 2 - 1); v[d] = prev; }
    rows.push(v);
  }
  return rows;
}

const cases = [];
for (const metric of ['l2', 'cosine']) {
  for (const sketchBits of [4, 8]) {
    const rows = seededRows(COUNT, DIM, SEED);
    const index = await Pikelet.create({ dim: DIM, maxElements: COUNT, metric, quantized: true });
    index.addBatch(rows);
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sketch-fx-'));
    const snap = path.join(tmp, 's.pnck');
    fs.writeFileSync(snap, index.export());
    index.dispose();
    const art = path.join(tmp, 'a.pikelet-sketch');
    Pikelet.buildSketchArtifactFile(snap, art, { sketchDims: 16, sketchBits, recommendedRerank: 64 });
    const bytes = fs.readFileSync(art);

    const artifact = await Pikelet.openSketchArtifactFile(art);
    // Reference queries: fixed seed, distinct from corpus.
    const queries = seededRows(6, DIM, SEED ^ 0x5a5a).map((v) => Array.from(v));
    const results = [];
    for (const q of queries) {
      for (const [k, C] of [[5, 32], [10, 64]]) {
        const r = (await artifact.search(new Float32Array(q), k, { rerank: C })).results;
        results.push({ k, rerank: C, ids: r.map((x) => x.id), dists: r.map((x) => Number(x.distance.toFixed(5))) });
      }
    }
    await artifact.close();
    fs.rmSync(tmp, { recursive: true, force: true });

    cases.push({
      metric, sketchBits,
      artifactBase64: bytes.toString('base64'),
      queries,
      results,
    });
  }
}

const banner = `// GENERATED by scripts/make-sketch-fixture.mjs — do not edit by hand.
// Sketch profile conformance fixture: a deterministic artifact and the
// reference reader's exact results. A conforming reader must reproduce these
// ids and distances (spec/SKETCH_PROFILE.md section 5).
'use strict';

`;
const out = banner + 'module.exports = ' + JSON.stringify({ count: COUNT, dim: DIM, seed: SEED, cases }, null, 2) + ';\n';
fs.writeFileSync(path.join(ROOT, 'test', 'fixtures', 'sketch_golden.js'), out);
const size = Buffer.byteLength(out);
console.log(`wrote test/fixtures/sketch_golden.js (${cases.length} cases, ${(size / 1024).toFixed(1)} KiB)`);
